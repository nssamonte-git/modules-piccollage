"""Regenerates core/rules/*.rules (the rule catalog) from the definitions below.

Each rule cites a threat id from core/rules/threat-index.tsv; the card path is
looked up from that index, so run core/tools/build-threat-index.sh first when the
threat library changes. Usage: python3 core/tools/generate-rules.py [repo-root]
Then run: sh tests/run-tests.sh
"""
import sys, os
repo = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
idx = {}
for line in open(os.path.join(repo, 'core/rules/threat-index.tsv')):
    p = line.rstrip('\n').split('\t')
    if p[0] != 'id': idx[p[0]] = p[5]

