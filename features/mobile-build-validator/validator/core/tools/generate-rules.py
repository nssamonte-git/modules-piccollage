def R(rid, threat, sev, typ, globs, pat, msg, flags='-', excl=None):
    assert threat in idx, threat
    f = [rid, threat, sev, typ, globs, pat, msg, idx[threat], flags]
    if excl: f.append(excl)
    for x in f: assert x and '\t' not in x and '\n' not in x, (rid, x)
    return '\t'.join(f)

