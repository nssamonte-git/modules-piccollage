class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent { MaterialTheme { Surface { DemoScreen(this@MainActivity) } } }
    }
}

private fun describe(result: Outcome<*>): String =
    when (result) {
        is Outcome.Success -> "Done"
        is Outcome.Failure -> result.error.message
    }

@Composable
private fun DemoScreen(activity: Activity) {
    var environment by remember { mutableStateOf<DemoEnvironment?>(null) }
    var loadError by remember { mutableStateOf("") }
    LaunchedEffect(Unit) {
        try {
            environment =
                withContext(Dispatchers.IO) { DemoEnvironment(activity.applicationContext) }
        } catch (e: Exception) {
            loadError = "Could not initialize the playground"
        }
    }
    val env = environment
    if (env == null) {
        Box(Modifier.fillMaxSize().padding(24.dp)) {
            Text(if (loadError.isEmpty()) "Loading creative playground…" else loadError)
        }
        return
    }
    var session by remember { mutableStateOf<EditSession>(HistorySession(env.document())) }
    val document by session.document.collectAsState()
    val page = document.pages.first()
    val scope = rememberCoroutineScope()
    var tab by remember { mutableStateOf("Editor") }
    var selected by remember { mutableStateOf<String?>("photo-layer") }
    var status by remember { mutableStateOf("") }
    var saved by remember { mutableStateOf<List<CreativeDocument>>(emptyList()) }
    var busy by remember { mutableStateOf(false) }
    LaunchedEffect(env) {
        val restored = env.reopen("demo", "sample-project")
        if (restored is Outcome.Success) {
            saved = listOf(restored.value)
            if (session.document.value.revision == 0L) session = HistorySession(restored.value)
        }
    }

    var placements by remember { mutableStateOf<List<Placement>>(emptyList()) }
    var exportState by remember { mutableStateOf<ExportState>(ExportState.Idle) }
    val videoState by env.video.state.collectAsState()
    var output by remember { mutableStateOf<File?>(null) }
    var exportJob by remember { mutableStateOf<Job?>(null) }
    val imageLayer = page.layers.firstOrNull { it.content is Content.Image }
    val textLayer = page.layers.firstOrNull { it.content is Content.Text }
    var maskPreview by remember { mutableStateOf<android.graphics.Bitmap?>(null) }
    DisposableEffect(Unit) { onDispose { maskPreview?.recycle() } }
    var proposal by remember { mutableStateOf<ToolCall?>(null) }
    val toolRunner = remember { ToolRunner(env.journal) }
    var imageJob by remember { mutableStateOf<ImageJob?>(null) }
    var generated by remember { mutableStateOf(false) }
    var aiBusy by remember { mutableStateOf(false) }
    var demoMode by remember { mutableStateOf("Success") }
    val provider =
        remember(demoMode) {
            object : ImageProvider {
                override suspend fun generate(job: ImageJob): Outcome<GeneratedImage> {
                    when (demoMode) {
                        "Failure" ->
                            return failure(CreativeError.Code.REMOTE, "Sample provider failure")
                        "Timeout" -> delay(2000)
                        "Delayed" -> delay(1000)
                    }
                    val id = "generated-${job.operationId}"
                    val bytes = env.bytes.getValue("photo").copyOf()
                    env.bytes[id] = bytes
                    return Outcome.Success(GeneratedImage(id, "image/png", 640, 480, bytes))
                }
            }
        }
    val imageRunner =
        remember(provider) {
            ImageJobRunner(
                env.journal,
                provider,
                AndroidGeneratedMediaValidator(),
                timeoutMs = 1500,
            )
        }
    val history = remember { LetteringHistory() }
    fun startExport(png: Boolean) {
        exportJob = scope.launch {
            exportState = ExportState.Running(0)
            try {
                val file =
                    File(activity.filesDir, "exports/${UUID.randomUUID()}.${if(png)"png"else"jpg"}")
                val result = StillExporter(env.renderer).export(document, page.id, file, png)
                if (result is Outcome.Success) {
                    output = file
                    exportState =
                        ExportState.Completed(file.path, if (png) "image/png" else "image/jpeg")
                } else exportState = ExportState.Failed(describe(result))
            } catch (e: CancellationException) {
                exportState = ExportState.Canceled
                throw e
            }
        }
    }
    Column(
        Modifier.fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(top = 32.dp, bottom = 24.dp)
    ) {
        Text(
            "Creative playground",
            style = MaterialTheme.typography.headlineMedium,
            modifier = Modifier.padding(horizontal = 16.dp),
        )
        Row(
            Modifier.horizontalScroll(rememberScrollState()).padding(8.dp),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            listOf(
                    "Editor",
                    "Projects",
                    "Templates",
                    "Layout",
                    "Effects",
                    "Masks",
                    "Text",
                    "Export",
                    "AI Tools",
                    "AI Images",
                )
                .forEach { label ->
                    FilterChip(
                        tab == label,
                        {
                            tab = label
                            status = ""
                        },
                        label = { Text(label) },
                    )
                }
        }
        HistoryControls(session, Modifier.padding(horizontal = 16.dp))
        CreativeCanvas(
            session,
            env.renderer,
            page.id,
            selected,
            { selected = it },
            Modifier.padding(16.dp),
        )
        when (tab) {
            "Editor" ->
                Column(Modifier.padding(16.dp)) {
                    Text(
                        "Select and drag a layer. Pinch to scale and rotate. Changes can be undone."
                    )
                    Row {
                        OutlinedButton(
                            onClick = {
                                selected?.let {
                                    status = describe(MoveLayer()(session, page.id, it, 10.0, 0.0))
                                }
                            }
                        ) {
                            Text("Move right")
                        }
                        OutlinedButton(
                            onClick = { status = describe(DuplicatePage()(session, page.id)) }
                        ) {
                            Text("Duplicate page")
                        }
                    }
                    OutlinedButton(
                        onClick = {
                            val id = UUID.randomUUID().toString()
                            status =
                                describe(
                                    AddDrawing()(
                                        session,
                                        page.id,
                                        id,
                                        listOf(
                                            Stroke(
                                                listOf(
                                                    Point(100.0, 180.0),
                                                    Point(200.0, 220.0),
                                                    Point(300.0, 180.0),
                                                ),
                                                8.0,
                                                0xffca603f.toInt(),
                                            )
                                        ),
                                    )
                                )
                        }
                    ) {
                        Text("Add a drawing")
                    }
                }
            "Projects" ->
                DocumentBrowser(
                    saved,
                    { id ->
                        scope.launch {
                            busy = true
                            when (val opened = env.reopen("demo", id)) {
                                is Outcome.Success -> {
                                    session = HistorySession(opened.value)
                                    status = "Draft reopened"
                                }
                                is Outcome.Failure -> status = opened.error.message
                            }
                            busy = false
                        }
                    },
                    {
                        scope.launch {
                            busy = true
                            status = describe(SaveDraft(env.repository)("demo", document))
                            if (status == "Done") saved = listOf(document)
                            busy = false
                        }
                    },
                    busy = busy,
                    status = status,
                )
            "Templates" -> {
                val recipes =
                    listOf(
                        Recipe(
                            "Simple title",
                            steps =
                                listOf(
                                    RecipeStep.Text(
                                        page.id,
                                        "recipe-${document.revision}",
                                        "Your story",
                                        50.0,
                                        140.0,
                                        400.0,
                                        70.0,
                                    )
                                ),
                        )
                    )
                TemplateGallery(
                    recipes,
                    0,
                    { recipe ->
                        scope.launch {
                            status =
                                describe(ApplyRecipe(null)("demo", session, recipe, emptyMap()))
                        }
                    },
                )
            }
            "Layout" ->
                LayoutSuggestions(
                    placements,
                    {
                        val photo = document.assets.first()
                        val result =
                            SuggestLayout()(
                                listOf(LayoutPhoto(photo)),
                                listOf(Slot("main", 20.0, 80.0, 600.0, 360.0)),
                            )
                        if (result is Outcome.Success) placements = result.value
                        status = describe(result)
                    },
                    { items ->
                        imageLayer?.let { layer ->
                            val p = items.first()
                            status =
                                describe(
                                    session.commit(
                                        EditRequest(
                                            document.revision,
                                            listOf(
                                                Edit.ReplaceLayer(
                                                    page.id,
                                                    layer.copy(
                                                        transform = Transform(p.slot.x, p.slot.y),
                                                        width = p.slot.width,
                                                        height = p.slot.height,
                                                        content =
                                                            Content.Image(
                                                                p.assetId,
                                                                Crop(
                                                                    p.crop.left,
                                                                    p.crop.top,
                                                                    p.crop.right,
                                                                    p.crop.bottom,
                                                                ),
                                                            ),
                                                    ),
                                                )
                                            ),
                                        )
                                    )
                                )
                        }
                    },
                    status = status,
                )
            "Effects" ->
                imageLayer?.let { layer ->
                    EffectControls(
                        layer.effects,
                        { status = describe(SetEffects()(session, page.id, layer.id, it)) },
                    )
                }
            "Masks" ->
                imageLayer?.let { layer ->
                    val source =
                        remember(layer.id) {
                            env.renderer.decode((layer.content as Content.Image).assetId)
                        }
                    DisposableEffect(source) { onDispose { source.recycle() } }
                    fun preview(mask: Mask) {
                        val next = AndroidMask().apply(source, mask)
                        maskPreview?.recycle()
                        maskPreview = next
                    }
                    LaunchedEffect(layer.mask) { preview(layer.mask ?: Mask()) }
                    MaskEditor(
                        layer.mask ?: Mask(),
                        source.width,
                        source.height,
                        maskPreview?.takeUnless { it.isRecycled }?.asImageBitmap(),
                        { preview(it) },
                        { status = describe(SetMask()(session, page.id, layer.id, it)) },
                    )
                }
            "Text" ->
                textLayer?.let { layer ->
                    GraphicTextEditor(
                        layer.content as Content.Text,
                        { status = describe(SetText()(session, page.id, layer.id, it)) },
                    )
                }
            "Export" -> {
                val current =
                    if (exportJob?.isActive == true && videoState is ExportState.Running) videoState
                    else exportState
                ExportControls(
                    current,
                    { startExport(true) },
                    { startExport(false) },
                    {
                        exportJob = scope.launch {
                            exportState = ExportState.Running(0)
                            try {
                                val timeline =
                                    Timeline(
                                        document.pages.take(2).map { Clip.Photo(it.id, 2_000_000) },
                                        if (document.pages.size > 1) 500_000 else 0,
                                        Music("music", 1_250_000, 250_000),
                                    )
                                val file =
                                    File(activity.filesDir, "exports/${UUID.randomUUID()}.mp4")
                                val result =
                                    env.video.export(
                                        document,
                                        timeline,
                                        file,
                                        VideoSettings(640, 480),
                                    )
                                if (result is Outcome.Success) {
                                    output = file
                                    exportState = ExportState.Completed(file.path, "video/mp4")
                                } else exportState = ExportState.Failed(describe(result))
                            } catch (e: CancellationException) {
                                exportState = ExportState.Canceled
                                throw e
                            }
                        }
                    },
                    { exportJob?.cancel() },
                    {
                        output?.let { file ->
                            val mime =
                                if (file.extension == "mp4") "video/mp4"
                                else if (file.extension == "png") "image/png" else "image/jpeg"
                            val uri =
                                FileProvider.getUriForFile(
                                    activity,
                                    "${activity.packageName}.exports",
                                    file,
                                )
                            status = describe(AndroidDelivery().share(activity, uri, mime))
                        }
                    },
                )
                OutlinedButton(
                    onClick = {
                        output
                            ?.takeIf { it.extension != "mp4" }
                            ?.let { file ->
                                val bitmap = android.graphics.BitmapFactory.decodeFile(file.path)
                                status = describe(AndroidDelivery().printImage(activity, bitmap))
                            }
                    },
                    enabled = output != null && output?.extension != "mp4",
                    modifier = Modifier.padding(16.dp),
                ) {
                    Text("Print image")
                }
            }
            "AI Tools" -> {
                OutlinedButton(
                    onClick = {
                        imageLayer?.let {
                            proposal =
                                ToolCall(
                                    UUID.randomUUID().toString(),
                                    UUID.randomUUID().toString(),
                                    "demo",
                                    document.id,
                                    document.revision,
                                    "move",
                                    mapOf(
                                        "pageId" to page.id,
                                        "layerId" to it.id,
                                        "x" to "40",
                                        "y" to "100",
                                    ),
                                )
                        }
                    },
                    modifier = Modifier.padding(16.dp),
                ) {
                    Text("Create sample proposal")
                }
                ToolProposalPanel(
                    proposal,
                    {
                        proposal?.let {
                            status = describe(toolRunner.execute(it, session))
                            proposal = null
                        }
                    },
                    { proposal = null },
                    status = status,
                )
            }
            "AI Images" -> {
                Row(Modifier.horizontalScroll(rememberScrollState())) {
                    listOf("Success", "Failure", "Delayed", "Timeout").forEach { mode ->
                        FilterChip(
                            demoMode == mode,
                            {
                                if (!aiBusy) {
                                    demoMode = mode
                                    generated = false
                                }
                            },
                            label = { Text(mode) },
                        )
                    }
                }
                ImageJobPanel(
                    aiBusy,
                    generated,
                    { prompt ->
                        imageLayer?.let { layer ->
                            val asset =
                                document.assets.first {
                                    it.id == (layer.content as Content.Image).assetId
                                }
                            val job =
                                ImageJob(
                                    UUID.randomUUID().toString(),
                                    "demo",
                                    document.id,
                                    document.revision,
                                    asset.id,
                                    asset.contentRevision,
                                    asset.width,
                                    asset.height,
                                    "replace",
                                    prompt,
                                )
                            imageJob = job
                            scope.launch {
                                aiBusy = true
                                generated = false
                                try {
                                    val result = imageRunner.start(job)
                                    status = describe(result)
                                    generated = result is Outcome.Success
                                    history.add(
                                        LetteringEntry(
                                            job.operationId,
                                            "demo",
                                            prompt,
                                            "sample",
                                            (result as? Outcome.Success)?.value?.assetId,
                                        )
                                    )
                                } finally {
                                    aiBusy = false
                                }
                            }
                        }
                    },
                    {
                        imageJob?.let {
                            imageRunner.cancel(it)
                            status = "Canceled"
                        }
                        generated = false
                    },
                    {
                        imageJob?.let { job ->
                            imageLayer?.let {
                                status = describe(imageRunner.accept(job, session, page.id, it.id))
                                generated = false
                            }
                        }
                    },
                    status = status,
                )
                Text("Local sample provider · no network calls", Modifier.padding(16.dp))
            }
        }
        if (tab !in listOf("Projects", "Layout", "AI Tools", "AI Images"))
            Text(status, Modifier.padding(16.dp))
    }
}
